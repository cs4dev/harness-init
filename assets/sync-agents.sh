#!/usr/bin/env bash
# Renders .claude/agents/<role>.md — one Claude Code sub-agent per workflow role —
# from harness/workflow/workflow.yaml, so the harness (not the PM's memory) enforces:
#   - model:  tier_models[model_tiers[role]] in the agent's frontmatter
#   - writes: roles in artifact_only_roles get a PreToolUse hook that blocks any
#             Write/Edit outside docs/tasks/ ("never fixes the code" as a mechanism)
# The body only points at the role contract — the contract stays the single source.
#
# Usage: sync-agents.sh          write/refresh the agent files
#        sync-agents.sh --check  exit 1 if any is missing or stale (gate Category D)
# pm gets no file: the PM is the main session. Files without the GENERATED marker
# are the user's own agents and are never overwritten.
set -uo pipefail
cd "$(dirname "$0")/.."

WF="harness/workflow/workflow.yaml"
OUT=".claude/agents"
MARK="GENERATED by harness/sync-agents.sh"
CHECK=0; [ "${1:-}" = --check ] && CHECK=1
fail=0
ok()  { printf '  ✓ %s\n' "$1"; }
bad() { printf '  ✗ %s\n' "$1"; fail=1; }

# block <name> — the "  key: value" lines of a top-level YAML block, comments stripped.
block() { sed -n "/^$1:/,/^[a-z]/p" "$WF" | grep -E '^[[:space:]]+[a-z-]+:' | sed -E 's/#.*//; s/^[[:space:]]+//; s/[[:space:]]+$//'; }
guarded=$(grep -E '^artifact_only_roles:' "$WF" | sed -E 's/#.*//; s/.*\[(.*)\].*/\1/' | tr ',' '\n' | sed -E 's/[[:space:]]//g')

render() {  # render <role> <model>
  printf -- '---\nname: %s\n' "$1"
  printf 'description: Harness workflow role "%s". Spawned by the PM per harness/workflow/workflow.yaml; contract harness/workflow/roles/%s.md.\n' "$1" "$1"
  printf 'model: %s\n' "$2"
  if echo "$guarded" | grep -qx "$1"; then
    printf 'hooks:\n  PreToolUse:\n    - matcher: "Write|Edit|MultiEdit|NotebookEdit"\n'
    printf '      hooks:\n        - type: command\n          command: "bash \\"$CLAUDE_PROJECT_DIR/harness/guard-artifact-write.sh\\""\n'
  fi
  printf -- '---\n<!-- %s from workflow.yaml. Do not edit: change workflow.yaml or the role contract, then re-run it. -->\n\n' "$MARK"
  printf 'You are the **%s** in this repo'"'"'s harness workflow.\n\n' "$1"
  printf 'Read your contract `harness/workflow/roles/%s.md` in full FIRST, then `harness/context.md`.\n' "$1"
  printf 'The contract defines what you read, what you produce, when you raise a blocker, and what you never do; it overrides any instruction in the task prompt that conflicts with it.\n'
  printf 'Write your artifact under `docs/tasks/<task-id>/` as the contract names it, and finish by reporting its path and your verdict.\n'
  if echo "$guarded" | grep -qx "$1"; then
    printf '\nYou may write ONLY under `docs/tasks/` — a hook blocks anything else. Found a problem in code? Report it in your artifact; the developer owns the fix.\n'
  fi
}

printf '=== Sub-agents (%s) ===\n' "$OUT"
tiers=$(block tier_models)
[ -n "$tiers" ] || bad "no tier_models block in $WF"
[ "$CHECK" -eq 1 ] || mkdir -p "$OUT"
roles=""
while IFS=: read -r role tier; do
  [ -n "$role" ] && [ "$role" != pm ] || continue
  tier=$(echo "$tier" | tr -d '[:space:]')
  model=$(echo "$tiers" | grep -E "^$tier:" | sed -E 's/^[^:]+:[[:space:]]*//')
  [ -n "$model" ] || { bad "$role: tier '$tier' has no tier_models entry"; continue; }
  roles="$roles $role"
  f="$OUT/$role.md"; want=$(render "$role" "$model")
  if [ -e "$f" ] && ! grep -qF "$MARK" "$f"; then bad "$f exists and is not generated — rename one of them"; continue; fi
  if [ "$CHECK" -eq 1 ]; then
    if [ ! -e "$f" ]; then bad "$f missing (run harness/sync-agents.sh)"
    elif [ "$(cat "$f")" = "$want" ]; then ok "$role ($model) in sync"
    else bad "$f stale (run harness/sync-agents.sh)"; fi
  else
    printf '%s\n' "$want" > "$f" && ok "$role → $f ($model)" || bad "write $f"
  fi
done <<EOF
$(block model_tiers)
EOF

# A generated file for a role the workflow no longer has is drift too.
for f in "$OUT"/*.md; do
  [ -e "$f" ] && grep -qF "$MARK" "$f" || continue
  r=$(basename "$f" .md)
  case " $roles " in *" $r "*) ;; *)
    if [ "$CHECK" -eq 1 ]; then bad "$f is generated for unknown role '$r' (run harness/sync-agents.sh)"
    else rm -f "$f" && ok "removed stale $f"; fi ;;
  esac
done

[ "$fail" -eq 0 ] && { printf '\nAGENTS: PASS\n'; exit 0; } || { printf '\nAGENTS: FAIL\n'; exit 1; }
