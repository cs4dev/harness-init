#!/usr/bin/env bash
# Persona split for multi-persona mockups (roles/ux-designer.md). The combined mockup
# is the ONE source the designer edits; this generates one file per persona beside it,
# all linked so the review bar's persona switch (P / Shift+P) steps between them.
#
#   source     <meta name="persona" content="a b …"> lists the personas (2+ to split).
#              Each <section data-screen> carries data-personas="a b": the personas whose
#              path includes that screen (untagged = combined file only). A persona's
#              file keeps its screens in source order, so its first one is its start.
#   persona    label  = "# Persona — <Label>" in docs/personas/<slug>.md (else the slug)
#              device = its "data-device`: <phone|tablet|desktop>" (else the source's)
#   output     <base>-<slug>.html beside <base>.html, marked GENERATED: persona meta = the
#              slug, body data-device, "· <Label>" in the title, and every data-goto to a
#              screen the persona doesn't have removed (the element stays, unwired). The
#              source and every output carry the same <meta name="mockup-files">.
#   layout     (the starter's) <section …data-screen…> opens on its own line, </section>
#              ends one; whole-line comments right above a screen travel with it;
#              <meta> tags sit one per line.
#
# Usage: split-mockup.sh [--check] [<mockup.html>…]
#   no files → every docs/mockups/*.html and docs/tasks/*/mockup.html that tags screens
#   with data-personas (generated files are skipped). --check writes nothing and exits 1
#   if any output, or the source's mockup-files meta, is missing or stale (the workflow
#   gate runs it — re-run without --check to fix).
set -uo pipefail
cd "$(dirname "$0")/.."

check=0; [ "${1:-}" = --check ] && { check=1; shift; }
fail=0
ok()  { printf '  ✓ %s\n' "$1"; }
bad() { printf '  ✗ %s\n' "$1"; fail=1; }
MARK='GENERATED by harness/split-mockup.sh'

meta() {  # meta <file> <name> — content of <meta name="<name>" content="…">
  tr '\n' ' ' < "$1" | grep -oiE "<meta[^>]*name=[\"']$2[\"'][^>]*>" | head -1 \
    | grep -oiE "content=[\"'][^\"']*[\"']" | sed -E "s/^content=[\"']//; s/[\"']$//"
}

# render <src> <files-meta> [<slug> <label> <device>] — the source (no slug) or one
# persona's file, on stdout.
render() {
  LC_ALL=C SLUG="${3:-}" LABEL="${4:-}" DEVICE="${5:-}" FILES="$2" SRC="$(basename "$1")" MARK="$MARK" awk '
    function attr(s, name,   r) {
      if (!match(s, name "=\"[^\"]*\"")) return ""
      r = substr(s, RSTART, RLENGTH); sub(/^[^"]*"/, "", r); sub(/"$/, "", r); return r
    }
    NR == FNR {  # pass 1: which screens this persona keeps
      if ($0 ~ /<section[^>]*data-screen=/) {
        id = attr($0, "data-screen"); n = split(attr($0, "data-personas"), p, /[[:space:]]+/)
        for (k = 1; k <= n; k++) if (p[k] == ENVIRON["SLUG"]) keep[id] = 1
      }
      next
    }
    function edit(s,   out, tok, id, at, len) {
      if (s ~ /<meta[^>]*name="mockup-files"/) return "\001"
      if (s ~ /<meta[^>]*name="persona"/) {
        if (slug != "") sub(/content="[^"]*"/, "content=\"" slug "\"", s)
        match(s, /^[[:space:]]*/)
        s = substr(s, 1, RLENGTH) "<meta name=\"mockup-files\" content=\"" ENVIRON["FILES"] "\">\n" s
      }
      if (slug == "") return s
      if (s ~ /<\/title>/) sub(/<\/title>/, " · " ENVIRON["LABEL"] "</title>", s)
      if (s ~ /<body/ && ENVIRON["DEVICE"] != "") sub(/data-device="[^"]*"/, "data-device=\"" ENVIRON["DEVICE"] "\"", s)
      out = ""
      while (match(s, /[[:space:]]?data-goto="[^"]*"/)) {
        at = RSTART; len = RLENGTH   # attr() calls match() and clobbers RSTART/RLENGTH
        tok = substr(s, at, len); id = attr(tok, "data-goto")
        out = out substr(s, 1, at - 1) ((id in keep) ? tok : "")
        s = substr(s, at + len)
      }
      return out s
    }
    function emit(s) { s = edit(s); if (s != "\001") print s }
    function flush(   k) { for (k = 1; k <= np; k++) emit(pend[k]); np = 0 }
    BEGIN { slug = ENVIRON["SLUG"]; inside = 0; np = 0; doc = 0 }
    {
      if (!doc && tolower($0) ~ /^<!doctype/) {
        print; doc = 1
        if (slug != "") print "<!-- " ENVIRON["MARK"] " from " ENVIRON["SRC"] " (" ENVIRON["LABEL"] ") — edit " ENVIRON["SRC"] ", not this file. -->"
        next
      }
      if (cmt) { print; if ($0 ~ /-->/) cmt = 0; next }   # multi-line comment: verbatim
      if (!inside && $0 ~ /<!--/ && $0 !~ /<!--.*-->/) { flush(); print; cmt = 1; next }
      if (inside) { if (take) emit($0); if ($0 ~ /<\/section>/) inside = 0; next }
      if ($0 ~ /<section[^>]*data-screen=/) {
        take = (slug == "") || (attr($0, "data-screen") in keep)
        if (take) flush(); else np = 0
        inside = ($0 !~ /<\/section>/)
        if (take) emit($0)
        next
      }
      if ($0 ~ /^[[:space:]]*$/ || $0 ~ /^[[:space:]]*<!--.*-->[[:space:]]*$/) { pend[++np] = $0; next }
      flush(); emit($0)
    }
    END { flush() }' "$1" "$1"
}

# put <path> <content-file> — write (or, with --check, compare).
put() {
  if [ "$check" -eq 1 ]; then
    cmp -s "$2" "$1" && ok "$1 up to date" || bad "$1 is missing or stale (run harness/split-mockup.sh)"
  else
    cmp -s "$2" "$1" && ok "$1 unchanged" || { cp "$2" "$1" && ok "wrote $1"; }
  fi
}

label() {  # label <slug> — "# Persona — <Label>" from the persona doc, else the slug
  local l=""; [ -f "docs/personas/$1.md" ] && \
    l=$(head -1 "docs/personas/$1.md" | sed -E 's/^#[[:space:]]*Persona[[:space:]]*(—|–|-)[[:space:]]*//; s/[[:space:]]+$//')
  case "$l" in ''|'#'*) echo "$1" ;; *) echo "$l" ;; esac
}

split_one() {
  local f=$1 base personas slug device files n tmp tagged
  printf '=== Split %s ===\n' "$f"
  [ -f "$f" ] || { bad "missing $f"; return; }
  grep -qF "$MARK" "$f" && { bad "$f is a generated file — split its source"; return; }
  base="${f%.html}"; personas=$(meta "$f" persona)
  tagged=$(grep -E '<section[^>]*data-screen=' "$f" | grep -oE 'data-personas="[^"]*"' | sed -E 's/^data-personas="//; s/"$//' | tr ' ' '\n' | grep -v '^$' | sort -u)
  if [ -z "$tagged" ]; then ok "no data-personas tags — single file, nothing to split"; return; fi
  n=$(echo $personas | wc -w | tr -d ' ')
  [ "$n" -ge 2 ] || { bad "data-personas used, but <meta name=\"persona\"> lists $n persona(s) (need 2+)"; return; }
  for slug in $tagged; do
    case " $personas " in *" $slug "*) ;; *) bad "data-personas names '$slug', which <meta name=\"persona\"> doesn't list" ;; esac
  done
  files="All screens=$(basename "$f")"
  for slug in $personas; do files="$files; $(label "$slug")=$(basename "$base")-$slug.html"; done
  tmp=$(mktemp -d)
  if ! render "$f" "$files" > "$tmp/src.html"; then bad "render of $f failed"; rm -rf "$tmp"; return; fi
  put "$f" "$tmp/src.html"
  for slug in $personas; do
    case " $(echo $tagged) " in *" $slug "*) ;; *) bad "persona '$slug' has no screen tagged data-personas=\"…$slug…\""; continue ;; esac
    device=$(grep -oE 'data-device`?:[[:space:]]*(phone|tablet|desktop)' "docs/personas/$slug.md" 2>/dev/null | head -1 | sed -E 's/.*[[:space:]:]//')
    render "$f" "$files" "$slug" "$(label "$slug")" "$device" > "$tmp/$slug.html" || { bad "render of $slug failed"; continue; }
    put "$base-$slug.html" "$tmp/$slug.html"
  done
  rm -rf "$tmp"
}

if [ $# -eq 0 ]; then
  for m in docs/mockups/*.html docs/tasks/*/mockup.html; do
    [ -e "$m" ] || continue
    grep -qF "$MARK" "$m" && continue
    grep -qE '<section[^>]*data-personas="' "$m" && set -- "$@" "$m"
  done
  [ $# -gt 0 ] || { printf '=== Split ===\n  - no mockup tags screens with data-personas\n\nSPLIT: PASS\n'; exit 0; }
fi
for f in "$@"; do split_one "$f"; done

[ "$fail" -eq 0 ] && { printf '\nSPLIT: PASS\n'; exit 0; } || { printf '\nSPLIT: FAIL\n'; exit 1; }
